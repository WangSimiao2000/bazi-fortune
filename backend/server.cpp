double getWeight(int year, int month, int day, int hour) {
    double total = 0;
    if (yearWeight[0].count(year)) total += yearWeight[0][year];
    if (monthWeight.count(month)) total += monthWeight[month];
    if (dayWeight.count(day)) total += dayWeight[day];
    if (hourWeight.count(hour)) total += hourWeight[hour];
    return total;
}

